#!/usr/bin/env node
/**
 * Generate the return-label data shipped in the customization package.
 *
 *   npm run return-labels        -> data/return-labels.json  →  src/assets/data/libraries.js
 *
 * WHY: the "Print return label" page (src/views/finder/assets/return-label/) needs
 * each library's internal-post address, keyed by Alma library code. Alma's API
 * does not expose those addresses, so the single source of truth is the
 * hand-maintained data/return-labels.json in this repo (git-versioned, reviewed).
 *
 * WHY A .js OUTPUT: Alma rejects .json files in customization packages, so the
 * data is written as a script that sets window.EC_LIBRARIES — the label page
 * loads it with a plain <script> tag.
 *
 * build.cjs runs this before every build, so the package can never ship stale
 * data; run it by hand only to preview the output.
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./view-context.cjs');

const IN_FILE = path.join(ROOT, 'data', 'return-labels.json');
const OUT_FILE = path.join(ROOT, 'src', 'assets', 'data', 'libraries.js');

function main() {
  const raw = JSON.parse(fs.readFileSync(IN_FILE, 'utf8'));

  // Validate as we copy: a typo here would only show up as a blank label for a patron.
  const libraries = {};
  for (const [code, entry] of Object.entries(raw)) {
    if (code.startsWith('_')) continue; // _comment and friends are documentation
    if (!entry || typeof entry !== 'object') throw new Error(`${code}: entry must be an object`);
    if (!entry.name) throw new Error(`${code}: "name" is required`);
    if (entry.returnAddress !== undefined) {
      if (!Array.isArray(entry.returnAddress) || !entry.returnAddress.every((l) => typeof l === 'string' && l.trim())) {
        throw new Error(`${code}: "returnAddress" must be a non-empty array of non-empty strings`);
      }
    }
    libraries[code] = { code, ...entry };
  }

  const out = { generatedAt: new Date().toISOString(), source: 'data/return-labels.json', libraries };
  const js =
    '/*\n' +
    '  GENERATED by scripts/return-labels.cjs from data/return-labels.json — do not edit by hand.\n' +
    '  Shipped as a .js file because Alma rejects .json in customization packages;\n' +
    '  consumers read window.EC_LIBRARIES.\n' +
    '*/\n' +
    'window.EC_LIBRARIES = ' + JSON.stringify(out, null, 2) + ';\n';

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, js);
  const withLabel = Object.values(libraries).filter((l) => l.returnAddress).length;
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}: ${Object.keys(libraries).length} libraries, ${withLabel} with a return label`);
}

try { main(); } catch (err) { console.error(`[return-labels] ${err.message}`); process.exit(1); }
