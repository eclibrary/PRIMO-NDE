#!/usr/bin/env node
/**
 * Generate the return-label data shipped in the customization package.
 *
 *   npm run return-labels        -> data/return-labels.json  →  src/assets/data/libraries.js
 *
 * WHY: the "Print return label" page (src/assets/return-label/) needs
 * each library's internal-post address, keyed by Alma library code. Alma's API
 * does not expose those addresses, so the single source of truth is the
 * hand-maintained data/return-labels.json in this repo (git-versioned, reviewed).
 *
 * WHY A .js OUTPUT: Alma rejects .json files in customization packages, so the
 * data is written as a script that sets window.EC_LIBRARIES — the label page
 * loads it with a plain <script> tag.
 *
 * build.cjs runs this before every build, so the package can never ship stale
 * data; run it by hand only to preview the output.
 *
 * SETTINGS.JS (Oct 2026): the same addresses are ALSO written into every view's
 * assets/settings.js ("libraries", by config-generate.cjs via readLibraries()
 * below), so colleagues can edit them in the package's settings editor. The
 * label page prefers settings.js and falls back to libraries.js (this file's
 * output) when settings.js cannot be read — e.g. an old package, or the page
 * opened from disk. Importing a settings.js in `npm run settings` writes edited
 * addresses back to data/return-labels.json (scripts/settings-ui/server.cjs).
 */
const fs = require('fs');
const path = require('path');
const { ROOT } = require('./view-context.cjs');

const IN_FILE = path.join(ROOT, 'data', 'return-labels.json');
const OUT_FILE = path.join(ROOT, 'src', 'assets', 'data', 'libraries.js');

/**
 * Validate a libraries map ({ CODE: { name, returnAddress?: string[] } }) and
 * return a clean copy without documentation keys (_comment …). Throws with the
 * library code in the message, because a typo would otherwise only show up as a
 * blank label for a patron. Shared with config-generate.cjs and the settings UI
 * import, so all three apply the same rules.
 */
function validateLibraries(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) throw new Error('libraries must be an object keyed by library code');
  const libraries = {};
  for (const [code, entry] of Object.entries(raw)) {
    if (code.startsWith('_')) continue; // _comment and friends are documentation
    if (!/^[A-Za-z0-9_-]+$/.test(code)) throw new Error(`"${code}": a library code has letters, digits, _ or - only`);
    if (!entry || typeof entry !== 'object') throw new Error(`${code}: entry must be an object`);
    if (!entry.name || typeof entry.name !== 'string') throw new Error(`${code}: "name" is required`);
    const clean = { name: entry.name };
    if (entry.returnAddress !== undefined) {
      if (!Array.isArray(entry.returnAddress) || !entry.returnAddress.every((l) => typeof l === 'string' && l.trim())) {
        throw new Error(`${code}: "returnAddress" must be a non-empty array of non-empty strings`);
      }
      clean.returnAddress = entry.returnAddress;
    }
    // Keep any other fields (e.g. an Alma "address" block the label page can use)
    // untouched — only name/returnAddress are checked.
    for (const [k, v] of Object.entries(entry)) if (!(k in clean)) clean[k] = v;
    libraries[code] = clean;
  }
  return libraries;
}

/** data/return-labels.json, validated: { CODE: { name, returnAddress? } }. */
function readLibraries() {
  return validateLibraries(JSON.parse(fs.readFileSync(IN_FILE, 'utf8')));
}

function main() {
  const libraries = {};
  for (const [code, entry] of Object.entries(readLibraries())) libraries[code] = { code, ...entry };

  const out = { generatedAt: new Date().toISOString(), source: 'data/return-labels.json', libraries };
  const js =
    '/*\n' +
    '  GENERATED by scripts/return-labels.cjs from data/return-labels.json — do not edit by hand.\n' +
    '  Shipped as a .js file because Alma rejects .json in customization packages;\n' +
    '  consumers read window.EC_LIBRARIES. The label page prefers the addresses in\n' +
    '  ../settings.js ("libraries", edited with the settings editor) and uses this\n' +
    '  file only when settings.js cannot be read.\n' +
    '*/\n' +
    'window.EC_LIBRARIES = ' + JSON.stringify(out, null, 2) + ';\n';

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, js);
  const withLabel = Object.values(libraries).filter((l) => l.returnAddress).length;
  console.log(`Wrote ${path.relative(ROOT, OUT_FILE)}: ${Object.keys(libraries).length} libraries, ${withLabel} with a return label`);
}

module.exports = { readLibraries, validateLibraries, IN_FILE };

// Run only when called directly (npm run return-labels / build.cjs), not when required.
if (require.main === module) {
  try { main(); } catch (err) { console.error(`[return-labels] ${err.message}`); process.exit(1); }
}
